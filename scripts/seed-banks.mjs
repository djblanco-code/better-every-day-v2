// Seed public.banks from supabase/seed/*.json.
//   node scripts/seed-banks.mjs            -> upserts through the API (needs NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SECRET_KEY in env)
//   node scripts/seed-banks.mjs --sql      -> prints SQL to stdout for the Supabase SQL editor (no secret needed)
// Idempotent: upsert on (track, item_id).
import { readFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

const FILES = [
  // LeetCode rows keep the top-12 company names only; full per-company frequencies stay in the seed file.
  ["leetcode", "recall-leetcode.json", (d) => d.problems.map((p) => [p.slug, slimProblem(p)])],
  ["python", "recall-python.json", (d) => d.items.map((i) => [i.id, i])],
  ["system_design", "recall-systemdesign.json", (d) => d.items.map((i) => [i.id, i])],
  ["dsa", "recall-dsa.json", (d) => d.items.map((i) => [i.id, i])],
  ["debugging", "recall-debugging.json", (d) => d.items.map((i) => [i.id, i])],
  ["curriculum", "recall-curriculum.json", (d) => d.weeks.map((w) => [String(w.week), w])],
  ["premium_statements", "recall-premium-statements.json", (d) => Object.entries(d).map(([slug, text]) => [slug, { text }])],
];
// Bank-level metadata (categories, company lists, program settings) stored under item_id "_meta".
const META = {
  leetcode: (d) => ({ categories: d.categories, companies: d.companies, company_lists: d.company_lists ?? {} }),
  curriculum: (d) => ({ program_weeks: d.program_weeks, daily_minutes: d.daily_minutes, principles: d.principles }),
};

function slimProblem(p) {
  const comps = Object.entries(p.companies ?? {}).sort((a, b) => (b[1]["6m"] ?? b[1].all ?? 0) - (a[1]["6m"] ?? a[1].all ?? 0));
  return {
    id: p.slug, title: p.title, difficulty: p.difficulty, topics: p.topics, url: p.url, lists: p.lists,
    topic: p.category || (p.topics?.[0] ?? ""), companies: comps.slice(0, 12).map(([c]) => c), company_count: comps.length,
  };
}

const rows = [];
for (const [track, file, pick] of FILES) {
  const d = JSON.parse(readFileSync(new URL(`../supabase/seed/${file}`, import.meta.url), "utf8"));
  for (const [id, data] of pick(d)) rows.push({ track, item_id: id, data });
  if (META[track]) rows.push({ track, item_id: "_meta", data: META[track](d) });
}

if (process.argv.includes("--sql")) {
  const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";
  const out = ["-- generated by scripts/seed-banks.mjs --sql", "begin;"];
  for (const r of rows) {
    out.push(
      `insert into public.banks (track, item_id, data) values (${lit(r.track)}, ${lit(r.item_id)}, ${lit(JSON.stringify(r.data))}::jsonb) on conflict (track, item_id) do update set data = excluded.data, updated_at = now();`,
    );
  }
  out.push("commit;", "select track, count(*) from public.banks group by track order by track;");
  process.stdout.write(out.join("\n") + "\n");
} else {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SECRET_KEY;
  if (!url || !key) {
    console.error("Set NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SECRET_KEY, or use --sql.");
    process.exit(2);
  }
  const sb = createClient(url, key, { auth: { persistSession: false } });
  for (let i = 0; i < rows.length; i += 200) {
    const { error } = await sb.from("banks").upsert(rows.slice(i, i + 200), { onConflict: "track,item_id" });
    if (error) throw error;
  }
  console.log(`upserted ${rows.length} rows`);
}
